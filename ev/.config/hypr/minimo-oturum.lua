-- Minimo OS as a session of its own, beside serpantinum: /usr/local/bin/minimo-session
-- starts Hyprland with this file (--config), so ~/.config/hypr/hyprland.lua is
-- not read, and serpantinum's config/ is not touched. Minimo's parts live in
-- ~/.config/hypr/minimo/ (links to ~/Proyectos/minimo-os, but for the monitors
-- and the keyboard, kept here).
-- This file is a link into ~/Proyectos/minimo-ayarlar, and Hyprland looks for
-- the modules beside where it really is: there, Minimo's own parts are
-- missing. They are looked for in ~/.config/hypr first, where all of them are.
package.path = os.getenv("HOME") .. "/.config/hypr/?.lua;" .. package.path

hl.config({ autogenerated = false })

-- XDG_CURRENT_DESKTOP is «Hyprland:Minimo» on purpose (the SDDM entry): Minimo's
-- own defaults, Ghostty's menu entry and the terminal hang on it. Hyprland
-- would warn at every start that it is managed from outside: it is meant.
hl.config({ misc = { disable_xdg_env_checks = true } })

-- At start: only what Minimo's services need goes to systemd —not all of this
-- session's environment, so nothing of it stays behind for Plasma or
-- serpantinum—, and minimo-session.target brings up the shell, the clipboard
-- history, the password dialogue and the keys on the wallpaper.
hl.on("hyprland.start", function()
	hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY DISPLAY HYPRLAND_INSTANCE_SIGNATURE XDG_CURRENT_DESKTOP XDG_SESSION_DESKTOP XDG_SESSION_TYPE")
	hl.exec_cmd("systemctl --user start minimo-session.target")
end)

